test('filas, columnas y subapartados conservan identidad y valores tras mover y borrar', async ({ browser }) => {
  const context = await mock.context(browser, mock.admin);
  const page = await context.newPage();
  await page.goto('/');
  const card = await createSection(page, 'Datos privados', ['Subapartados', 'Tabla configurable']);
  await card.getByRole('button', { name: 'Añadir subapartado' }).click();
  await card.getByRole('button', { name: 'Añadir subapartado' }).click();
  await card.getByRole('textbox', { name: 'Título del apartado 9.1' }).fill('Primero');
  await card.getByRole('textbox', { name: 'Contenido del apartado 9.1' }).fill('Contenido primero');
  await card.getByRole('textbox', { name: 'Título del apartado 9.2' }).fill('Segundo');
  await card.getByRole('textbox', { name: 'Contenido del apartado 9.2' }).fill('Contenido segundo');
  await card.getByRole('button', { name: 'Añadir columna' }).click();
  await card.getByRole('textbox', { name: 'Nombre de columna 1' }).fill('Clave');
  await card.getByRole('textbox', { name: 'Nombre de columna 2' }).fill('Valor');
  await card.getByRole('button', { name: 'Añadir fila' }).click();
  await card.getByRole('button', { name: 'Añadir fila' }).click();
  for (const [name, value] of [['Clave, fila 1', 'K1'], ['Valor, fila 1', 'V1'], ['Clave, fila 2', 'K2'], ['Valor, fila 2', 'V2']]) await card.getByRole('textbox', { name }).fill(value);
  const before = await exportCopy(page);
  const id = before.sectionOrder.at(-1);
  const firstSubId = before.customSections[id].subsections[0].id;
  const secondSubId = before.customSections[id].subsections[1].id;
  const firstRowId = before.customSections[id].table.rows[0].id;
  const secondRowId = before.customSections[id].table.rows[1].id;
  const firstColumnId = before.customSections[id].table.columns[0].id;
  const secondColumnId = before.customSections[id].table.columns[1].id;
  await card.getByRole('button', { name: 'Mover columna Clave a la derecha' }).click();
  await card.getByRole('button', { name: 'Bajar fila 1' }).click();
  await card.getByRole('button', { name: 'Subir apartado 2' }).click();
  const moved = await exportCopy(page);
  expect(moved.customSections[id].subsections.map((item) => item.id)).toEqual([secondSubId, firstSubId]);
  expect(moved.customSections[id].table.columns.map((item) => item.id)).toEqual([secondColumnId, firstColumnId]);
  expect(moved.customSections[id].table.rows.map((item) => item.id)).toEqual([secondRowId, firstRowId]);
  expect(moved.customSections[id].table.rows.find((item) => item.id === firstRowId)[firstColumnId]).toBe('K1');
  expect(moved.customSections[id].table.rows.find((item) => item.id === secondRowId)[secondColumnId]).toBe('V2');
  await card.getByRole('button', { name: 'Eliminar columna Valor' }).click();
  await card.getByRole('button', { name: 'Eliminar fila 1' }).click();
  await card.getByRole('button', { name: 'Eliminar apartado 2' }).click();
  const after = await exportCopy(page);
  expect(after.customSections[id].table.columns.map((item) => item.id)).toEqual([firstColumnId]);
  expect(after.customSections[id].table.rows.map((item) => item.id)).toEqual([firstRowId]);
  expect(after.customSections[id].table.rows[0][secondColumnId]).toBeUndefined();
  expect(after.customSections[id].subsections.map((item) => item.id)).toEqual([secondSubId]);
  await context.close();
});

