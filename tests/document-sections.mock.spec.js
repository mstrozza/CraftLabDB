async function createSection(page, title, blocks = ['Descripción']) {
  await page.getByRole('button', { name: 'Añadir sección' }).first().click();
  const dialog = page.getByRole('dialog', { name: 'Añadir sección' });
  await dialog.getByRole('textbox', { name: 'Nombre de la sección' }).fill(title);
  for (const label of ['Descripción', 'Subapartados', 'Tabla configurable', 'Código COBOL']) {
    const checkbox = dialog.getByRole('checkbox', { name: label });
    if (blocks.includes(label)) await checkbox.check();
    else await checkbox.uncheck();
  }
  await dialog.getByRole('button', { name: 'Crear sección' }).click();
  return page.locator('section.section-card').last();
}

async function exportCopy(page) {
  await page.getByRole('button', { name: 'Exportar' }).click();
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: /Copia editable/ }).click();
  return JSON.parse(await readFile(await (await download).path(), 'utf8'));
}

